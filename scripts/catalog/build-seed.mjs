#!/usr/bin/env node
/**
 * Generates supabase/seed.sql from catalog/catalog.json.
 *
 *   npm run catalog:seed            # write supabase/seed.sql
 *   npm run catalog:seed -- --check # exit 1 if seed.sql is out of date (for CI)
 *
 * The output is deterministic (fixed UUIDs, no timestamps) and idempotent: running
 * seed.sql twice, or on top of the previous demo seed, leaves the same catalogue.
 * It writes categories, products, variants, images, collections, the store settings
 * row and one demo promo code (WELCOME10). No reviews and no user accounts.
 */
import fs from "node:fs";
import path from "node:path";
import {
  ROOT,
  loadCatalog,
  validateCatalog,
  stableUuid,
  categoryRow,
  productRow,
  variantRow,
  imageRow,
  collectionRow,
  SETTINGS_COLUMNS,
  RETIRED_DEMO_PRODUCTS,
  RETIRED_DEMO_CATEGORIES,
} from "./lib.mjs";

const OUT = path.join(ROOT, "supabase", "seed.sql");
const DEMO_PROMO = { code: "WELCOME10", discount_type: "percentage", discount_value: 10, min_order_amount: 1000 };

const catalog = loadCatalog();
const problems = validateCatalog(catalog);
for (const p of catalog.products) if (RETIRED_DEMO_PRODUCTS.includes(p.slug)) problems.push(`product ${p.slug}: slug is on the retired demo list`);
if (problems.length) {
  console.error(`catalog.json has ${problems.length} problem(s):\n- ${problems.join("\n- ")}`);
  process.exit(1);
}

// ── SQL literals ────────────────────────────────────────────────
const q = (v) => (v == null ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v == null ? "NULL" : String(Number(v)));
const b = (v) => (v ? "true" : "false");
const arr = (list) => (list && list.length ? `ARRAY[${list.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const json = (v) => `${q(JSON.stringify(v ?? {}))}::jsonb`;
const catId = (slug) => `(SELECT id FROM categories WHERE slug = ${q(slug)})`;
const prodId = (slug) => `(SELECT id FROM products WHERE slug = ${q(slug)})`;
const colId = (slug) => `(SELECT id FROM collections WHERE slug = ${q(slug)})`;
const list = (items) => items.map(q).join(", ");
const values = (rows) => rows.map((r) => `  (${r.join(", ")})`).join(",\n");

const out = [];
const emit = (s = "") => out.push(s);
const section = (title) => emit(`\n-- ── ${title} ${"─".repeat(Math.max(4, 58 - title.length))}`);

emit(`-- ============================================================
-- ShiftSouq: demo catalogue seed
-- GENERATED by scripts/catalog/build-seed.mjs from catalog/catalog.json.
-- Do not edit by hand: change catalog/catalog.json and run
--   npm run catalog:seed
-- Safe to run more than once. Products, variants and images are matched by
-- slug / SKU; no user accounts, reviews or orders are created.
-- Photos: Unsplash (free licence); credits are in catalog/catalog.json.
-- ============================================================

BEGIN;`);

// 1. Retire the previous demo catalogue (only touches its known slugs).
section("Previous demo catalogue");
emit(`-- Order lines keep their own name, price and image, so removing these is safe for old orders.
DELETE FROM products WHERE slug IN (${list(RETIRED_DEMO_PRODUCTS)});`);
for (const slug of RETIRED_DEMO_CATEGORIES)
  emit(`DELETE FROM categories c WHERE c.slug = ${q(slug)}
  AND NOT EXISTS (SELECT 1 FROM products p WHERE p.category_id = c.id)
  AND NOT EXISTS (SELECT 1 FROM categories k WHERE k.parent_id = c.id);`);

// 2. Categories: parents first, then children (parent looked up by slug).
section("Categories");
const catCols = ["id", "parent_id", "slug", "name_en", "name_ar", "description_en", "description_ar", "image_url", "sort_order", "is_active", "is_featured"];
const catUpdate = catCols.filter((c) => c !== "id" && c !== "slug").map((c) => `${c} = EXCLUDED.${c}`).join(",\n  ");
for (const level of [false, true]) {
  const rows = catalog.categories
    .filter((c) => Boolean(c.parent) === level)
    .map((c) => {
      const r = categoryRow(c);
      return [q(stableUuid("category", c.slug)), c.parent ? catId(c.parent) : "NULL", q(r.slug), q(r.name_en), q(r.name_ar), q(r.description_en), q(r.description_ar), q(r.image_url), n(r.sort_order), b(r.is_active), b(r.is_featured)];
    });
  emit(`INSERT INTO categories (${catCols.join(", ")}) VALUES
${values(rows)}
ON CONFLICT (slug) DO UPDATE SET
  ${catUpdate};`);
}

// 3. Products.
section("Products");
const prodCols = [
  "id", "category_id", "slug", "name_en", "name_ar", "description_en", "description_ar", "base_price", "sale_price", "brand",
  "is_featured", "is_new", "is_active", "details_en", "details_ar", "care_en", "care_ar", "tags", "size_system",
  "seo_title_en", "seo_title_ar", "seo_description_en", "seo_description_ar",
];
const prodRows = catalog.products.map((p) => {
  const r = productRow(p);
  return [
    q(p.id ?? stableUuid("product", p.slug)), catId(p.category), q(r.slug), q(r.name_en), q(r.name_ar), q(r.description_en), q(r.description_ar),
    n(r.base_price), n(r.sale_price), q(r.brand), b(r.is_featured), b(r.is_new), b(r.is_active), q(r.details_en), q(r.details_ar),
    q(r.care_en), q(r.care_ar), arr(r.tags), q(r.size_system), q(r.seo_title_en), q(r.seo_title_ar), q(r.seo_description_en), q(r.seo_description_ar),
  ];
});
emit(`INSERT INTO products (${prodCols.join(", ")}) VALUES
${values(prodRows)}
ON CONFLICT (slug) DO UPDATE SET
  ${prodCols.filter((c) => c !== "id" && c !== "slug").map((c) => `${c} = EXCLUDED.${c}`).join(",\n  ")};`);

// 4. Variants (matched by SKU; variants of these products that left the catalogue are removed).
section("Variants");
const allSkus = catalog.products.flatMap((p) => p.variants.map((v) => v.sku));
const productSlugs = catalog.products.map((p) => p.slug);
emit(`DELETE FROM product_variants
WHERE product_id IN (SELECT id FROM products WHERE slug IN (${list(productSlugs)}))
  AND sku NOT IN (${list(allSkus)});`);
const varCols = ["id", "product_id", "sku", "size", "color_en", "color_ar", "color_hex", "stock", "price_override", "position"];
for (const p of catalog.products) {
  const rows = p.variants.map((v, i) => {
    const r = variantRow(p, v, i);
    return [q(stableUuid("variant", v.sku)), prodId(p.slug), q(r.sku), q(r.size), q(r.color_en), q(r.color_ar), q(r.color_hex), n(r.stock), n(r.price_override), n(r.position)];
  });
  emit(`INSERT INTO product_variants (${varCols.join(", ")}) VALUES
${values(rows)}
ON CONFLICT (sku) DO UPDATE SET
  ${varCols.filter((c) => c !== "id" && c !== "sku").map((c) => `${c} = EXCLUDED.${c}`).join(", ")};`);
}

// 5. Images (replaced as a set for each catalogue product).
section("Images");
emit(`DELETE FROM product_images WHERE product_id IN (SELECT id FROM products WHERE slug IN (${list(productSlugs)}));`);
const imgCols = ["id", "product_id", "url", "alt_text_en", "alt_text_ar", "is_primary", "sort_order", "color_en"];
for (const p of catalog.products) {
  const rows = p.images.map((img, i) => {
    const r = imageRow(img, i);
    return [q(stableUuid("image", `${p.slug}:${i}`)), prodId(p.slug), q(r.url), q(r.alt_text_en), q(r.alt_text_ar), b(r.is_primary), n(r.sort_order), q(r.color_en)];
  });
  emit(`INSERT INTO product_images (${imgCols.join(", ")}) VALUES
${values(rows)};`);
}

// 6. Collections.
section("Collections");
const colCols = ["id", "slug", "title_en", "title_ar", "description_en", "description_ar", "image_url", "is_active", "sort_order"];
const colRows = catalog.collections.map((c) => {
  const r = collectionRow(c);
  return [q(stableUuid("collection", c.slug)), q(r.slug), q(r.title_en), q(r.title_ar), q(r.description_en), q(r.description_ar), q(r.image_url), b(r.is_active), n(r.sort_order)];
});
emit(`INSERT INTO collections (${colCols.join(", ")}) VALUES
${values(colRows)}
ON CONFLICT (slug) DO UPDATE SET
  ${colCols.filter((c) => c !== "id" && c !== "slug").map((c) => `${c} = EXCLUDED.${c}`).join(", ")},
  updated_at = now();`);
emit(`DELETE FROM collection_products WHERE collection_id IN (SELECT id FROM collections WHERE slug IN (${list(catalog.collections.map((c) => c.slug))}));`);
const cpRows = catalog.collections.flatMap((c) => c.products.map((slug, i) => [colId(c.slug), prodId(slug), n(i)]));
emit(`INSERT INTO collection_products (collection_id, product_id, position) VALUES
${values(cpRows)};`);

// 7. Store settings (single row, id = 1).
section("Store settings");
const s = catalog.settings;
emit(`INSERT INTO store_settings (id, ${SETTINGS_COLUMNS.join(", ")}) VALUES
  (1, ${SETTINGS_COLUMNS.map((c) => json(s[c])).join(",\n     ")})
ON CONFLICT (id) DO UPDATE SET
  ${SETTINGS_COLUMNS.map((c) => `${c} = EXCLUDED.${c}`).join(", ")},
  updated_at = now();`);

// 8. Demo promo code.
section("Demo promo code");
emit(`INSERT INTO promocodes (id, code, discount_type, discount_value, min_order_amount, is_active) VALUES
  (${q(stableUuid("promocode", DEMO_PROMO.code))}, ${q(DEMO_PROMO.code)}, ${q(DEMO_PROMO.discount_type)}, ${n(DEMO_PROMO.discount_value)}, ${n(DEMO_PROMO.min_order_amount)}, true)
ON CONFLICT (code) DO UPDATE SET
  discount_type = EXCLUDED.discount_type, discount_value = EXCLUDED.discount_value,
  min_order_amount = EXCLUDED.min_order_amount, is_active = true;`);

emit("\nCOMMIT;");
const sql = out.join("\n") + "\n";

if (process.argv.includes("--check")) {
  // Compare without line-ending differences (git may check the file out with CRLF on Windows).
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== sql) {
    console.error("supabase/seed.sql is out of date. Run: npm run catalog:seed");
    process.exit(1);
  }
  console.log("supabase/seed.sql is up to date.");
} else {
  fs.writeFileSync(OUT, sql);
  const variants = catalog.products.reduce((t, p) => t + p.variants.length, 0);
  const images = catalog.products.reduce((t, p) => t + p.images.length, 0);
  console.log(
    `Wrote ${path.relative(ROOT, OUT)}: ${catalog.categories.length} categories, ${catalog.products.length} products, ${variants} variants, ${images} images, ${catalog.collections.length} collections.`,
  );
}
