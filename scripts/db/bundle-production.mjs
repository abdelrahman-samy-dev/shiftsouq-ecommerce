#!/usr/bin/env node
/**
 * Bundles the migrations a live database still needs into files you can paste
 * into the Supabase SQL editor (Dashboard → SQL → New query → Run).
 *
 *   node scripts/db/bundle-production.mjs [--since 20260101000200]
 *
 * Output: supabase/production/
 *   01-roles.sql    — adds the super_admin role (must run and commit on its own:
 *                     Postgres can't use a new enum value in the same transaction)
 *   02-upgrade.sql  — every other migration after --since, in order, in one
 *                     transaction (all-or-nothing)
 *
 * Every migration is idempotent, so re-running a file is safe.
 * Prefer `npx supabase db push` when the project is linked with the CLI.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const args = process.argv.slice(2);
const sinceIdx = args.indexOf("--since");
const since = sinceIdx >= 0 ? args[sinceIdx + 1] : "20260101000200";

const dir = "supabase/migrations";
const files = readdirSync(dir)
  .filter((f) => /^\d{14}_.+\.sql$/.test(f) && f.slice(0, 14) > since)
  .sort();

if (!files.length) {
  console.log(`Nothing newer than ${since}.`);
  process.exit(0);
}

const isEnumStep = (f) => /ALTER TYPE\s+\w+\s+ADD VALUE/i.test(readFileSync(join(dir, f), "utf8"));
const enumFiles = files.filter(isEnumStep);
const rest = files.filter((f) => !enumFiles.includes(f));

const banner = (title, list) =>
  `-- ${title}\n-- Generated by scripts/db/bundle-production.mjs from:\n${list.map((f) => `--   ${f}`).join("\n")}\n\n`;

const body = (list) =>
  list.map((f) => `-- ════ ${f} ════\n${readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n").trim()}\n`).join("\n");

mkdirSync("supabase/production", { recursive: true });
writeFileSync(
  "supabase/production/01-roles.sql",
  banner("Step 1 of 2 — run alone first.", enumFiles) + body(enumFiles),
);
writeFileSync(
  "supabase/production/02-upgrade.sql",
  banner("Step 2 of 2 — run after step 1. All-or-nothing.", rest) + "BEGIN;\n\n" + body(rest) + "\nCOMMIT;\n",
);
console.log(`Step 1: ${enumFiles.length} file(s); step 2: ${rest.length} file(s) → supabase/production/`);
