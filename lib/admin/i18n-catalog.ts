export function getCatalogText(locale: string): CatalogText {
  return locale === "ar" ? ar : en;
}

/** Replaces {name} placeholders. */
export function fmt(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in values ? String(values[k]) : m));
}

/** Translated error for a key, with a generic fallback. */
export function catalogError(text: CatalogText, key: string | undefined): string {
  return (key && text.error[key]) || text.error.generic;
}

/** Western digits in both languages. */
export function formatCount(n: number, locale: string): string {
  return n.toLocaleString(locale === "ar" ? "ar-EG-u-nu-latn" : "en-US");
}

export function formatShortDate(iso: string | null | undefined, locale: string): string {
  if (!iso) return "—";
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return "—";
  return d.toLocaleDateString(locale === "ar" ? "ar-EG-u-nu-latn" : "en-GB", {
    timeZone: "Africa/Cairo",
    day: "numeric",
    month: "short",
    year: "numeric",
  });
}
